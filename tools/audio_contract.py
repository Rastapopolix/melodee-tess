"""Generate/check the explicit four-track voice reservations (no device access)."""
import argparse,json,itertools
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render(data):
    assert data['categories']==['PROPHET','FM6','CZ1','SID','808','909']
    caps=data['caps'];assert len(caps)==1296
    for cat,row in zip(itertools.product(range(6),repeat=4),caps):
        assert len(row)==4 and all(v in (1,2) for v in row)
        assert all(v==2 for c,v in zip(cat,row) if c>=4)
    return ('/* SPDX-License-Identifier: GPL-3.0-only */\n'
            '/* Generated by tools/audio_contract.py. Index: (((a*6+b)*6+c)*6+d).\n'
            ' * Total sounding slots include releases; drum parts reserve two circuits. */\n'
            'static const uint8_t audio_voice_contract[1296][4]={\n'+
            ''.join('    {'+','.join(map(str,v))+'},\n' for v in caps)+'};\n')
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    path=ROOT/'firmware/src/audio_voice_contract.h';content=render(json.loads((ROOT/'tools/audio_voice_contract.json').read_text()))
    if a.check:
        if path.read_text()!=content:raise SystemExit('Voice contract header differs; run tools/audio_contract.py')
    else:path.write_text(content)
    print('Voice contract: 1296 reservations, release slots and two drum circuits: OK')
if __name__=='__main__':main()
